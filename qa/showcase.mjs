// Walks every screen of every role in the demo build: each nav page and each tab,
// at desktop, phone width and dark theme. Fails on console errors, sideways scroll
// or a page without a heading. Run: npm run build:demo && node qa/showcase.mjs
import { createRequire } from 'node:module';
const { chromium } = createRequire(import.meta.url)('playwright');
import { mkdirSync } from 'node:fs';
import { resolve } from 'node:path';

const url = 'file://' + resolve('apps/web/dist-demo/index.html');
const out = resolve(process.env.SHOTS ?? 'qa/shots/showcase');
mkdirSync(out, { recursive: true });
const errors = [], failures = [];
const check = (c, m) => { if (!c) failures.push(m); };
const browser = await chromium.launch();
const ROLES = [['Mrs. S. Sujatha', 'principal'], ['Mr. K. Karthik', 'teacher'], ['Mrs. P. Priya', 'parent'], ['Arun Kumar P', 'student']];
let pages = 0;

for (const [who, role] of ROLES) {
  for (const mode of [{ width: 1360, height: 900, theme: 'light', tag: 'desk' }, { width: 390, height: 844, theme: 'dark', tag: 'phone' }]) {
    const ctx = await browser.newContext({ viewport: { width: mode.width, height: mode.height }, colorScheme: mode.theme });
    const page = await ctx.newPage();
    page.on('pageerror', (e) => errors.push(`${role}/${mode.tag}: ${e.message}`));
    page.on('console', (m) => { if (m.type() === 'error') errors.push(`${role}/${mode.tag}: ${m.text()}`); });
    await page.goto(url);
    await page.getByRole('button', { name: new RegExp(who) }).click();
    await page.waitForSelector('.rail');
    const menu = page.getByRole('button', { name: 'Open menu' });
    const labels = await page.locator('.rail nav button').allTextContents();
    for (const label of labels) {
      if (await menu.isVisible()) await menu.click();
      await page.locator('.rail nav button', { hasText: label }).first().click();
      await page.waitForTimeout(350);
      const name = `${role}-${mode.tag}-${label.replace(/\W+/g, '-').toLowerCase()}`;
      check(await page.locator('main h1').count() > 0, `${name}: no heading`);
      const tabs = page.locator('main [role=tab]');
      const n = await tabs.count();
      for (let t = 0; t < n; t++) {
        await tabs.nth(t).click();
        await page.waitForTimeout(200);
        const w = await page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth);
        check(w <= 1, `${name} tab ${t}: scrolls sideways by ${w}px`);
        if (mode.tag === 'desk') await page.screenshot({ path: `${out}/${name}-t${t}.png` });
      }
      if (!n) {
        const w = await page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth);
        check(w <= 1, `${name}: scrolls sideways by ${w}px`);
        if (mode.tag === 'desk') await page.screenshot({ path: `${out}/${name}.png` });
      }
      pages++;
    }
    await ctx.close();
  }
}

